'use strict';
/**
 * ArtifactStore: one JSON + one Markdown file per finished agent turn, in <store>/artifacts/.
 * index.json keeps a short entry per artifact, so the history list is fast.
 */
const fs = require('fs');
const path = require('path');

function fmtDuration(ms) {
  if (ms == null) return '-';
  const s = Math.round(ms / 1000);
  if (s < 60) return `${s}s`;
  const m = Math.floor(s / 60);
  if (m < 60) return `${m}m ${s % 60}s`;
  return `${Math.floor(m / 60)}h ${m % 60}m`;
}

function iso(ts) {
  return ts ? new Date(ts).toISOString().replace('T', ' ').slice(0, 19) + ' UTC' : '-';
}

function toMarkdown(a) {
  const L = [];
  const list = (items, empty = '_None_') => (items.length ? items.map((x) => `- ${x}`) : [empty]);
  L.push(`# ${a.agentName}`, '');
  L.push(`| Field | Value |`, `|---|---|`);
  L.push(`| Artifact | \`${a.id}\` |`);
  L.push(`| Agent | ${a.kind === 'main' ? 'Main session' : `Subagent (${a.agentType})`} \`${a.agentId}\` |`);
  L.push(`| Status | **${a.status}** |`);
  L.push(`| Turn | ${a.turn} |`);
  L.push(`| Started | ${iso(a.startedAt)} |`);
  L.push(`| Ended | ${iso(a.endedAt)} |`);
  L.push(`| Duration | ${fmtDuration(a.durationMs)} |`);
  if (a.model) L.push(`| Model | ${a.model} |`);
  L.push('', '## Task', '', '> ' + String(a.prompt || '').split('\n').join('\n> '), '');
  L.push('## Summary', '', a.summary, '');
  L.push('## Modified files', '');
  L.push(...list(a.filesModified.map((f) => `\`${f.path}\` (${f.edits} edits, ${f.writes} writes)`)));
  L.push('', '## Files read', '', ...list(a.filesRead.map((f) => `\`${f}\``)));
  L.push('', '## Tasks', '');
  L.push(...list([
    ...a.tasks.completed.map((t) => `[x] ${t}`),
    ...a.tasks.in_progress.map((t) => `[~] ${t}`),
    ...a.tasks.pending.map((t) => `[ ] ${t}`),
  ]));
  if (a.subagents.length) {
    L.push('', '## Subagents', '', ...a.subagents.map((s) => `- ${s.name} (${s.type}) — ${s.status}`));
  }
  L.push('', '## Tool usage', '', ...list(Object.entries(a.tools).sort((x, y) => y[1] - x[1]).map(([k, v]) => `${k}: ${v}`)));
  L.push('', '## Issues encountered', '', ...list(a.issues.map((i) => `**${i.tool}** — ${i.message}`), '_No issues_'));
  L.push('', `_Generated by AI Manager at ${iso(a.generatedAt)}_`, '');
  return L.join('\n');
}

class ArtifactStore {
  constructor(storeDir) {
    this.dir = path.join(storeDir, 'artifacts');
    this.indexFile = path.join(this.dir, 'index.json');
    this.index = null;
  }

  load() {
    if (this.index) return this.index;
    try { this.index = JSON.parse(fs.readFileSync(this.indexFile, 'utf8')); } catch { this.index = {}; }
    return this.index;
  }

  /** Signature of the facts that matter: rewrite only when the turn changed. */
  static signature(a) {
    return [a.status, a.endedAt, a.filesModified.length, a.issues.length, Object.values(a.tools).reduce((s, n) => s + n, 0), a.summary.length, a.subagents.map((s) => s.status).join(',')].join('|');
  }

  write(artifact) {
    const index = this.load();
    const sig = ArtifactStore.signature(artifact);
    const prev = index[artifact.id];
    if (prev && prev.sig === sig) return false;
    fs.mkdirSync(this.dir, { recursive: true });
    const full = { ...artifact, generatedAt: Date.now() };
    fs.writeFileSync(path.join(this.dir, `${artifact.id}.json`), JSON.stringify(full, null, 2));
    fs.writeFileSync(path.join(this.dir, `${artifact.id}.md`), toMarkdown(full));
    index[artifact.id] = {
      id: artifact.id, sig, agentId: artifact.agentId, agentName: artifact.agentName, kind: artifact.kind,
      agentType: artifact.agentType, status: artifact.status, turn: artifact.turn,
      prompt: String(artifact.prompt || '').slice(0, 200), endedAt: artifact.endedAt, durationMs: artifact.durationMs,
      filesModified: artifact.filesModified.length, issues: artifact.issues.length,
      tasksCompleted: artifact.tasks.completed.length, generatedAt: full.generatedAt,
    };
    this.dirty = true;
    if (!this.batch) this.commit();
    return true;
  }

  /** Group many writes into one index update. */
  begin() { this.batch = true; }

  commit() {
    this.batch = false;
    if (!this.dirty) return;
    this.dirty = false;
    // Merge with the file on disk: a hook process may have added entries since we loaded.
    let disk = {};
    try { disk = JSON.parse(fs.readFileSync(this.indexFile, 'utf8')); } catch { /* first write */ }
    this.index = Object.assign(disk, this.index);
    const tmp = this.indexFile + '.' + process.pid + '.tmp';
    fs.writeFileSync(tmp, JSON.stringify(this.index));
    fs.renameSync(tmp, this.indexFile);
    try { this.indexMtime = fs.statSync(this.indexFile).mtimeMs; } catch { /* ignore */ }
  }

  /** Newest first. */
  list() {
    // Another process (a hook) may have written new artifacts: reload when the index file changed.
    try {
      const m = fs.statSync(this.indexFile).mtimeMs;
      if (m !== this.indexMtime) { this.index = null; this.indexMtime = m; }
    } catch { /* no index yet */ }
    return Object.values(this.load())
      .map(({ sig, ...rest }) => rest)
      .sort((x, y) => (y.endedAt || 0) - (x.endedAt || 0));
  }

  get(id) {
    if (!/^[\w.-]+$/.test(id)) return null;
    try {
      const json = JSON.parse(fs.readFileSync(path.join(this.dir, `${id}.json`), 'utf8'));
      const md = fs.readFileSync(path.join(this.dir, `${id}.md`), 'utf8');
      return { ...json, markdown: md };
    } catch { return null; }
  }
}

module.exports = { ArtifactStore, toMarkdown, fmtDuration };
